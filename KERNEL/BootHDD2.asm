BITS 16
ORG 0x7E00
;TODO- Get MMAP
STG2:
	MOV AX,0x2000
	MOV ES,AX
	MOV AX,0x3
	INT 0x10
	MOV DL,0x80
	MOV DH,0
	MOV CL,11
	MOV CH,0
	MOV AL,60 ;30 KB
	XOR BX,BX
	MOV AH,2
	INT 0x13
	JC STG2_ERROR
	CALL DETECT_MEM_SIZE
	LGDT [BHDD_DESCRIPT_GDT]
	MOV EAX,CR0
	BTC EAX,0
	MOV CR0,EAX
	JMP 0x8:START32
	
DETECT_MEM_SIZE:
	MOV AX,0xE801
	INT 0x15
	JC @1
	CMP EBX,0
	JE mb16
	SHL EBX,6
	MOV ECX,0x9000
	MOV DWORD [ECX],EBX	
	RET
mb16:
	MOV ECX,0x9000
	MOV DWORD [ECX],16*1024
	RET
@1:
	MOV BYTE [ERROR],1
	
BITS 32
START32:
	MOV AX,0x10
	MOV ES,AX
	MOV DS,AX
	MOV FS,AX
	MOV GS,AX
	MOV SS,AX
	MOV ESP,0x7FEFC
	XOR EAX,EAX
	XOR EDX,EDX
	XOR ECX,ECX
	XOR EBX,EBX
	XOR EDI,EDI
	XOR ESI,ESI
	XOR EBP,EBP
	JMP 0x20000
	
STG2_PRINT:
	LODSB
	TEST AL,AL
	JZ .END
	MOV BYTE [DS:SI],AL
	INC SI
	MOV BYTE [DS:SI],0x4
	INC SI
	JMP STG2_PRINT
.END:
	RET
	
STG2_ERROR:
	MOV SI,FAIL
	CALL STG2_PRINT
OS_HALT:
	HLT
	JMP OS_HALT

BHDD_GDT_START:
	DQ 0

	DW 0xFFFF			;limit quad
	DW 0x0000			;base quad
	DB 0x00				;base byte
	DB 0x9A				;type byte
	DB 0xCF				;flags
	DB 0x00				;base byte
	
	DW 0xFFFF			;limit quad
	DW 0x0000			;base quad
	DB 0x00				;base byte
	DB 0x92				;type byte		
	DB 0xCF				;flags
	DB 0x00
BHDD_GDT_END:
BHDD_DESCRIPT_GDT:
	DW BHDD_GDT_END - BHDD_GDT_START - 1
	DD BHDD_GDT_START

ERROR DB 0
	
DBG DB "MTOS Boot Loader stg2",0
FAIL DB "FAILED",0
