BITS 16
ORG 0x7E00
SECTR2:
	XOR AX,AX
	MOV DS,AX
	XOR ECX,ECX
	MOV CX,50
	CLC
	LEA SI,SKYOS
	CALL BHDD_PRINT
	MOV AH,0x42
	MOV DL,0x80
	LEA SI,DAP_ENTRY
	INT 0x13
	JC DIE
	JMP 0xffff
DIE:
	LEA SI,SKYOS_FAIL
	CALL BHDD_PRINT
	HLT
	JMP $		
BHDD_PRINT:
	LODSB
	CMP AL,0
	JZ RR
	MOV AH,0xE
	INT 0x10
	JMP BHDD_PRINT
RR:
	RET

SKYOS DB "STAGE 2",13,10,0
SKYOS_FAIL DB "FAILED.",13,10,0

DAP_ENTRY DB 16,0,1,0
DAP_TRANSFER DW 0,0xffff
LBA_TRANSFER DQ 0
