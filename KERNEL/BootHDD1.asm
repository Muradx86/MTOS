BITS 16
ORG 0x7C00
BHDD_MAIN:
	CLI
	CLD
	XOR EAX,EAX
	MOV DS,AX
	MOV ES,AX
	MOV SS,AX
	MOV SP,0x9000
	LEA SI,SKYOS
	CALL BHDD_PRINT
	STI
	IN AL,0x92
	OR AL,2
	OUT 0x92,AL
	MOV DH,0
	MOV CH,0
	MOV CL,3
	MOV AL,30
	MOV BX,0x2000
	MOV DL,0x80
	MOV AH,2
	INT 0x13
	XOR EAX,EAX
	XOR EBX,EBX
	XOR ECX,ECX
	XOR EDX,EDX
	XOR ESI,ESI
	JMP 0x2000
BHDD_ERROR:
	LEA SI,SKYOS_DIE
	CALL BHDD_PRINT
HALT:
	HLT
	JMP HALT
BHDD_PRINT:
	LODSB
	CMP AL,0
	JZ RR
	MOV AH,0xE
	INT 0x10
	JMP BHDD_PRINT
RR:
	RET
SKYOS_DIE DB "FAIL",13,10,0
SKYOS DB "SkyOS Boot Loader",13,10,0
TIMES 510-($-$$) DB 0
DW 0xAA55
