BITS 16
ORG 0x7C00
BHDD_MAIN:
	CLI
	XOR EAX,EAX
	MOV DS,AX
	MOV SS,AX
	MOV ES,AX
	MOV SP,0x9000
	
	MOV DX,0x92
	IN AL,DX
	OR AL,2
	OUT DX,AL
	MOV AX,3
	INT 0x10
	LEA SI,SKYOS
	CALL BHDD_PRINT
	MOV DX,0x3F8
	MOV AL,'A'
	OUT DX,AL
	
	MOV BX,0x7E00
	MOV DH,0
	MOV CH,0
	MOV CL,2
	MOV AL,10
	MOV DL,0x80
	MOV AH,2
	INT 0x13
	JC BHDD_ERROR
	JMP 0x7E00
BHDD_ERROR:
	LEA SI,SKYOS_DIE
	CALL BHDD_PRINT
HALT:
	HLT
	JMP HALT
BHDD_PRINT:
	LODSB
	CMP AL,0
	JZ RR
	MOV AH,0xE
	INT 0x10
	JMP BHDD_PRINT
RR:
	RET
SKYOS_DIE DB "FAIL",13,10,0
SKYOS DB "SkyOS Boot Loader stg1",13,10,0
TIMES 510-($-$$) DB 0
DW 0xAA55
