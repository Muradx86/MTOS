global Sin
global Cos
global Round
global Sqrt
global PowOfTwo
Sin:
	PUSH EBP
	MOV EBP,ESP
	FLD QWORD [EBP+8]
	FSIN
	FSTP QWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	MOV DWORD EDX,[EBP-16]
	POP EBP
	RET

Cos:
	PUSH EBP
	MOV EBP,ESP
	FLD QWORD [EBP+8]
	FCOS
	FSTP QWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	MOV DWORD EDX,[EBP-16]
	POP EBP
	RET

Round:
	;By default FPU flag, it will round the nearest.
	PUSH EBP
	MOV EBP,ESP
	FLD QWORD [EBP+8]
	FRNDINT
	FISTP DWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	POP EBP
	RET

Sqrt:
	PUSH EBP
	MOV EBP,ESP
	FLD QWORD [EBP+8]
	FSQRT
	FSTP QWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	MOV DWORD EDX,[EBP-16]
	POP EBP
	RET

PowOfTwo:
	PUSH EBP
	MOV EBP,ESP
	FILD DWORD [EBP+8]
	FLD1
	FXCH
	FYL2X
	FRNDINT
	FISTP DWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	POP EBP
	RET	
