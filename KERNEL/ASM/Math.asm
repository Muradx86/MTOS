;Simple Math routines.
global Sin
global Cos
global Round
global Sqrt
global Log2
global Pow
global Sqr
global _Abs
_Abs:
	;Underscore for not mismatching NASM built-in func.
	PUSH EBP
	MOV EBP,ESP
	FILD DWORD [EBP+8]
	FABS
	FISTP DWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	POP EBP
	RET
	
Sin:
	PUSH EBP
	MOV EBP,ESP
	FLD QWORD [EBP+8]
	FSIN
	FSTP QWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	MOV DWORD EDX,[EBP-16]
	POP EBP
	RET

Cos:
	PUSH EBP
	MOV EBP,ESP
	FLD QWORD [EBP+8]
	FCOS
	FSTP QWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	MOV DWORD EDX,[EBP-16]
	POP EBP
	RET

Round:
	;By default FPU flag, it will round the nearest.
	PUSH EBP
	MOV EBP,ESP
	FLD QWORD [EBP+8]
	FRNDINT
	FISTP DWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	POP EBP
	RET

Sqrt:
	PUSH EBP
	MOV EBP,ESP
	FLD QWORD [EBP+8]
	FSQRT
	FSTP QWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	MOV DWORD EDX,[EBP-16]
	POP EBP
	RET

Log2:
	PUSH EBP
	MOV EBP,ESP
	FILD DWORD [EBP+8]
	FLD1
	FXCH
	FYL2X
	FRNDINT
	FISTP DWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	POP EBP
	RET	

Sqr:
	;Square
	PUSH EBP
	MOV EBP,ESP
	FILD DWORD [EBP+8]
	FMUL ST0,ST0
	FISTP DWORD [EBP-12]
	MOV DWORD EAX,[EBP-12]
	POP EBP
	RET

Pow:
	;ECX=POWER EDX=NUM
	PUSH EBP
	MOV EBP,ESP
	MOV DWORD EDX,[EBP+8]
	TEST EDX,EDX ;Zero to power?
	JZ @@1
	CMP EDX,1 ;One to power?
	JZ	@@2
	MOV DWORD ECX,[EBP+12]
	DEC ECX
@@0:
	IMUL DWORD EDX,[EBP+8]
	LOOP @@0
	MOV EAX,EDX
	POP EBP
	RET
@@1:
	MOV EAX,0
	POP EBP
	RET
@@2:
	MOV EAX,1
	POP EBP
	RET
