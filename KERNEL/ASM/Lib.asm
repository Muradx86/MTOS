ComplementBit:
	PUSH EBP
	MOV EBP,ESP
	MOV BYTE AL,[EBP+12]
	MOVZX EAX,AL
	BTC DWORD [EBP+8],EAX
	POP EBP
	RET

colorize:
	MOV EDI,0xb8000
	MOV AX,' ' | (0x9F << 8)
	MOV ECX,2000
	CLD
	REP STOSW
	RET

colorize_dbg:
	MOV EDI,0xb8000
	MOV AX,0
	MOV ECX,4000
	CLD
	REP STOSB
	RET

ToU32:
	PUSH EBP
	MOV EBP,ESP
	MOV WORD AX,[EBP+8]
	MOVZX EAX,AX
	POP EBP
	RET

StrLen:
	PUSH EBP
	MOV EBP,ESP
	XOR ECX,ECX
	MOV DWORD ESI,[EBP+8]
.@@0:
	LODSB
	OR AL,AL
	JZ .@@1
	INC ECX
	JMP .@@0
.@@1:
	MOV EAX,ECX
	POP EBP
	RET

Reverse:
	PUSH EBP
	MOV EBP,ESP
	MOV DWORD EBX,[EBP+8]
	PUSH EBX
	CALL StrLen ;STRLEN IN EAX
	MOV ECX,EAX 
	POP EDX ;EBX
	STD
.@@1:
	LODSB
	XCHG AL,[EDX]
	INC EDX
	LOOP .@@1
	CLD
	POP EBP
	RET
	
atoi:
	PUSH EBP
	MOV EBP,ESP
	CLD
	XOR EBX,EBX
	XOR EDX,EDX
	XOR ECX,ECX
	MOV DWORD ESI,[EBP+8]
.@@1:
	LODSB
	TEST AL,AL
	JZ .@@2
	SUB AL,'0'
	MOVZX EAX,AL
	IMUL ECX,10
	ADD ECX,EAX
	JMP .@@1
.@@2:
	MOV EAX,ECX
	LEAVE
	RET
	
StrCpy:
	PUSH EBP
	MOV EBP,ESP
	MOV DWORD EDI,[EBP+8]
	MOV DWORD ESI,[EBP+12]
	CLD
.@@1:
	LODSB
	TEST AL,AL
	JZ .@@2
	MOV BYTE [EDI],AL
	INC EDI
	JMP .@@1
.@@2:
	MOV DWORD EAX,[EBP+18]
	POP EBP
	RET

read_flag:
	PUSHFD
	POP EAX
	RET

Bt:
	PUSH EBP
	MOV EBP,ESP
	MOV DWORD ESI,[EBP+8]
	MOV DWORD EAX,[EBP+12]
	BT ESI,EAX
	PUSHFD
	POP EAX
	AND EAX,(1<<0)
	POP EBP
	RET

KbdHasKey: ;Kbd driver helper
WLOOP:
	IN AL,0x64
	AND AL,1
	JZ WLOOP
	MOV EAX,1 ;Returns 1 when available
	RET
