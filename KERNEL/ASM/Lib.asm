testif:
	PUSH EBP
	MOV EBP,ESP
	XOR EDX,EDX
	MOV EAX,1
	CPUID
	POP EBP
	RET

random_hw:
	MOV EDI,0x8000
	RDRAND AX
	AND AX,0xff
	MOV WORD [EDI],AX
	RET

rdrandU8:
	PUSH EDI
	PUSH EAX
	MOV EDI,0x8000
	RDRAND AX
	AND AX,0xff
	MOV BYTE [EDI],AL
	POP EAX
	POP EDI
	RET

rdrandU16:
	PUSH EDI
	PUSH EAX
	MOV EDI,0x8000
	RDRAND AX
	MOV WORD [EDI],AX
	POP EAX
	POP EDI
	
rdrandU32:
	PUSH EDI
	PUSH EAX
	MOV EDI,0x8000
	RDRAND EAX
	MOV DWORD [EDI],EAX
	POP EAX
	POP EDI
	RET

MemSet:
	PUSH EBP
	MOV EBP,ESP
	PUSH EAX
	PUSH ECX
	PUSH EDI
	CLD
	MOV DWORD EDI,[EBP+8]
	MOV EBX,EDI
	MOV BYTE AL,[EBP+12]
	MOV DWORD ECX,[EBP+16]
	REP STOSB
	POP EDI
	POP ECX
	POP EAX
	POP EBP
	MOV EAX,EBX
	RET

