ComplementBit:
	PUSH EBP
	MOV EBP,ESP
	MOV BYTE AL,[EBP+12]
	MOVZX EAX,AL
	BTC DWORD [EBP+8],EAX
	POP EBP
	RET

colorize:
	MOV EDI,0xb8000
	MOV AX,' ' | (0x9F << 8)
	MOV ECX,2000
	CLD
	REP STOSW
	RET

colorize_dbg:
	MOV EDI,0xb8000
	MOV AX,0
	MOV ECX,4000
	CLD
	REP STOSB
	RET

ToU32:
	PUSH EBP
	MOV EBP,ESP
	MOV WORD AX,[EBP+8]
	MOVZX EAX,AX
	POP EBP
	RET

kstrlen:
	PUSH EBP
	MOV EBP,ESP
	XOR ECX,ECX
	LEA ESI,[EBP+8]
@@0:
	LODSB
	TEST AL,AL
	JZ @@@1
	JMP @@0
@@@1:
	MOV EAX,ECX
	POP EBP
	RET

Reverse:
	PUSH EBP
	MOV EBP,ESP
	LEA ESI,[EBP+8]
	MOV EDX,ESI
	XOR ECX,ECX
@@1:
	LODSB
	TEST AL,AL
	JZ @@2
	INC ECX
	JMP @@1
@@2:
	MOV BYTE AL,[ESI-1]
	STD
@@3:
	XCHG BYTE AL,[EDX]
	LODSB
	INC EDX
	LOOP @@3
	CLD
	MOV DWORD EAX,[EBP+8]
	POP EBP
	RET
